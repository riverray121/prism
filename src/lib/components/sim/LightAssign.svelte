<script lang="ts">
  import { programLabel } from "$lib/mapping/labels";
  import {
    PALETTES,
    resolvePalette,
    SINGLE_PALETTE_ID,
  } from "$lib/showgen/palettes";
  import { ALGORITHMS } from "$lib/showgen/registry";
  import { roomLights } from "$lib/sim/room";
  import { MAPPING_PREFIX } from "$lib/sim/show";
  import { inspection } from "$lib/state/inspection.svelte";
  import { mapping } from "$lib/state/mapping.svelte";
  import {
    activeRoom,
    activeShow,
    assignLight,
    regenerate,
    setSimAlgorithm,
    setSimPalette,
    selectItem,
    sim,
  } from "$lib/state/sim.svelte";

  // Which program drives each light of the room for the open song, plus
  // Regenerate (algorithm + palette). Every change saves immediately.

  const room = $derived(activeRoom());
  const show = $derived(activeShow());
  const lights = $derived(room ? roomLights(room) : []);
  // Copied hardware programs show under their mapping entry, not twice.
  const roomPrograms = $derived(
    (show?.programs ?? []).filter((p) => !p.id.startsWith(MAPPING_PREFIX)),
  );
  const mappingPrograms = $derived(mapping.doc?.programs ?? []);
  const generatedBy = $derived(show?.generator?.algorithm ?? null);

  // The color a light's program is painted with, for its swatch.
  function swatch(programId: string | undefined): string | null {
    const p = show?.programs.find((x) => x.id === programId);
    if (!p) return null;
    // A section-bound hue shows its first section's color.
    const first = (v: unknown, scale: number): number | null => {
      if (typeof v === "number") return v;
      const step = (
        v as
          | { transform?: { categorical?: { map: Record<string, number> } }[] }
          | undefined
      )?.transform?.find((t) => t.categorical)?.categorical;
      const value = step ? Object.values(step.map)[0] : undefined;
      return value === undefined ? null : value * scale;
    };
    const hue = first(p.channels.hue, 360);
    if (hue === null) return null;
    const s = first(p.channels.saturation, 1) ?? 0.8;
    return `oklch(0.72 ${(s * 0.32).toFixed(3)} ${hue.toFixed(1)})`;
  }

  function pickPalette(id: string): void {
    setSimPalette(
      id === SINGLE_PALETTE_ID
        ? { id, color: sim.palette.color ?? "#2B6CC4" }
        : { id },
    );
  }
</script>

<section class="flex flex-col gap-2 p-3 pt-0">
  <p class="text-xs font-medium uppercase tracking-wide text-ink-faint">Show</p>
  {#if inspection.songId === null}
    <p class="text-sm text-ink-faint">Open a song to play its show here.</p>
  {:else if sim.doc === null || !room}
    <p class="text-sm text-ink-faint">Loading…</p>
  {:else}
    <div class="flex flex-col gap-1.5 rounded border border-edge p-2">
      <label
        class="flex items-center justify-between gap-2 text-xs text-ink-muted"
      >
        Algorithm
        <select
          value={sim.algorithm}
          onchange={(e) => setSimAlgorithm(e.currentTarget.value)}
          class="min-w-0 rounded border border-edge bg-app px-1.5 py-0.5 text-ink"
        >
          {#each ALGORITHMS as a (a.id)}
            <option value={a.id} title={a.description}>{a.label}</option>
          {/each}
        </select>
      </label>
      <label
        class="flex items-center justify-between gap-2 text-xs text-ink-muted"
      >
        Palette
        <span class="flex items-center gap-1">
          {#if sim.palette.id === SINGLE_PALETTE_ID}
            <input
              type="color"
              value={sim.palette.color ?? "#2B6CC4"}
              oninput={(e) =>
                setSimPalette({
                  id: SINGLE_PALETTE_ID,
                  color: e.currentTarget.value,
                })}
              class="h-5 w-6 cursor-pointer rounded border border-edge bg-app"
            />
          {/if}
          <select
            value={sim.palette.id}
            onchange={(e) => pickPalette(e.currentTarget.value)}
            class="min-w-0 rounded border border-edge bg-app px-1.5 py-0.5 text-ink"
          >
            {#each PALETTES as p (p.id)}
              <option value={p.id}>{p.name}</option>
            {/each}
            <option value={SINGLE_PALETTE_ID}>Single color</option>
          </select>
        </span>
      </label>
      <div class="flex h-2 overflow-hidden rounded-sm">
        {#each resolvePalette(sim.palette).colors as c, i (i)}
          <span class="flex-1" style="background: {c}"></span>
        {/each}
      </div>
      <button
        onclick={regenerate}
        title="Replace this room's show for the open song"
        class="rounded border border-edge px-2 py-1 text-xs text-ink-muted hover:text-ink"
      >
        {show ? "Regenerate" : "Generate"}
      </button>
      {#if generatedBy}
        <p class="text-xs text-ink-faint">Generated by {generatedBy}</p>
      {/if}
      {#if sim.error}
        <p class="text-xs text-danger">{sim.error}</p>
      {/if}
    </div>

    {#if !show}
      <p class="text-sm text-ink-faint">
        Generating once the song's tracks load…
      </p>
    {:else if lights.length === 0}
      <p class="text-sm text-ink-faint">
        No lights in this room. Drag some in.
      </p>
    {:else}
      <ul class="flex flex-col gap-1">
        {#each lights as light (light.id)}
          {@const current = show.patch[light.id] ?? ""}
          {@const color = swatch(current)}
          <li class="flex items-center gap-1.5">
            <span
              class="h-3 w-3 shrink-0 rounded-sm border border-edge"
              style={color ? `background: ${color}` : ""}
            ></span>
            <button
              onclick={() => selectItem(light.id)}
              class="min-w-0 flex-1 truncate text-left text-sm hover:text-accent {sim.selectedItemId ===
              light.id
                ? 'text-accent'
                : ''}"
              title="Select in the room"
            >
              {light.name}
            </button>
            <select
              value={current}
              onchange={(e) =>
                assignLight(light.id, e.currentTarget.value || null)}
              class="w-32 shrink-0 rounded border border-edge bg-app px-1 py-0.5 text-xs"
            >
              <option value="">Off</option>
              {#if roomPrograms.length}
                <optgroup label="Room show">
                  {#each roomPrograms as p (p.id)}
                    <option value={p.id}>{programLabel(p)}</option>
                  {/each}
                </optgroup>
              {/if}
              {#if mappingPrograms.length}
                <optgroup label="Song mapping">
                  {#each mappingPrograms as p (p.id)}
                    <option value={MAPPING_PREFIX + p.id}
                      >{programLabel(p)}</option
                    >
                  {/each}
                </optgroup>
              {/if}
            </select>
          </li>
        {/each}
      </ul>
    {/if}
  {/if}
</section>
